#!/usr/bin/env bash
# Regenerates Formula/silk.rb from the newest published Silk compiler release.
#
#   scripts/update-formula.sh [tag]
#
# Without a tag, the release is picked as install.sh picks it: the latest stable release, or the
# newest published dev release while no stable release exists. Each target archive is downloaded,
# its minisign signature is checked against the Silk release key, and its SHA-256 is pinned in the
# formula. Prints the selected tag on stdout.
#
# Environment:
#   GITHUB_TOKEN   optional; raises the GitHub API rate limit
set -euo pipefail

repo=silk-lang/silk
# The release signing key, published as minisign.pub at the root of silk-lang/silk.
minisign_public_key=RWQefAo9Dbb8LrlLPaqWdRNlX5th2l7r+4WYhxRNbe5K5URDUht1XUDs
targets=(aarch64-apple-darwin x86_64-unknown-linux-gnu aarch64-unknown-linux-gnu)
root=$(cd "$(dirname "$0")/.." && pwd)

fail() {
  printf 'update-formula: %s\n' "$*" >&2
  exit 1
}

for tool in curl jq minisign sha256sum; do
  command -v "$tool" > /dev/null 2>&1 || fail "this script needs $tool"
done

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# Prints the body of a GitHub API GET; exits 4 on 404 so a missing stable release is not an error.
api() {
  local auth=()
  [ -n "${GITHUB_TOKEN:-}" ] && auth=(-H "Authorization: Bearer $GITHUB_TOKEN")
  local status
  status=$(curl -sS -o "$tmp/response.json" -w '%{http_code}' \
    -H 'Accept: application/vnd.github+json' "${auth[@]}" \
    "https://api.github.com/repos/$repo/$1") || fail "cannot reach the GitHub API"
  case "$status" in
    200) cat "$tmp/response.json" ;;
    404) return 4 ;;
    *) fail "GitHub API returned HTTP $status for $1" ;;
  esac
}

encode() { printf '%s' "$1" | sed 's/+/%2B/g'; }

newest_dev() {
  local page=1 listing
  : > "$tmp/releases.json"
  while :; do
    listing=$(api "releases?per_page=100&page=$page") || fail "cannot list releases"
    printf '%s\n' "$listing" >> "$tmp/releases.json"
    [ "$(printf '%s' "$listing" | jq length)" -ge 100 ] || break
    page=$((page + 1))
  done
  jq -rs '[.[][]
      | select(.draft == false and .prerelease == true)
      | .tag_name
      | select(test("^v(0|[1-9][0-9]*)\\.(0|[1-9][0-9]*)\\.(0|[1-9][0-9]*)-dev\\.[1-9][0-9]*\\+[a-f0-9]{12}$"))]
    | sort_by(ltrimstr("v") | split("+")[0] | split("-dev.") | (.[0] | split(".") | map(tonumber)) + [(.[1] | tonumber)])
    | last // empty' "$tmp/releases.json"
}

tag=${1:-}
if [ -z "$tag" ]; then
  if latest=$(api releases/latest); then
    tag=$(printf '%s' "$latest" | jq -r '.tag_name')
    printf '%s' "$latest" | jq -e '.prerelease == false and .draft == false' > /dev/null ||
      fail "the latest release $tag is not stable"
  else
    [ "$?" = 4 ] || exit 1
    tag=$(newest_dev)
  fi
fi
[ -n "$tag" ] || fail "no published compiler release is available"
case "$tag" in v[0-9]*) ;; *) fail "not a compiler release tag: $tag" ;; esac

metadata=$(api "releases/tags/$(encode "$tag")") || fail "cannot find release $tag"
printf '%s' "$metadata" | jq -e '.draft == false' > /dev/null || fail "$tag is a draft"
version=${tag#v}

declare -A url sha
for target in "${targets[@]}"; do
  archive="silk-$version-$target.tar.gz"
  url[$target]="https://github.com/$repo/releases/download/$(encode "$tag")/$(encode "$archive")"
  curl -fsSL -o "$tmp/$archive" "${url[$target]}" || fail "cannot download $archive"
  curl -fsSL -o "$tmp/$archive.minisig" "${url[$target]}.minisig" || fail "cannot download $archive.minisig"
  comment=$(minisign -V -P "$minisign_public_key" -m "$tmp/$archive" -x "$tmp/$archive.minisig" -Q) ||
    fail "$archive is not signed by the Silk release key"
  [ "$comment" = "silk $tag $archive" ] || fail "the signature of $archive is for another file: $comment"
  sha[$target]=$(sha256sum "$tmp/$archive" | cut -d' ' -f1)
  # GitHub's own digest must agree with what was downloaded.
  digest=$(printf '%s' "$metadata" | jq -r --arg name "$archive" '.assets[] | select(.name == $name) | .digest // empty')
  [ -z "$digest" ] || [ "$digest" = "sha256:${sha[$target]}" ] || fail "$archive digest differs from GitHub's $digest"
done

cat > "$root/Formula/silk.rb" <<RUBY
# Generated by scripts/update-formula.sh from $tag. Do not edit by hand.
class Silk < Formula
  desc "Systems language compiled through LLVM to native code and WebAssembly"
  homepage "https://github.com/silk-lang/silk"
  version "$version"
  license "MIT"

  on_macos do
    depends_on arch: :arm64

    url "${url[aarch64-apple-darwin]}"
    sha256 "${sha[aarch64-apple-darwin]}"
  end

  on_linux do
    on_intel do
      url "${url[x86_64-unknown-linux-gnu]}"
      sha256 "${sha[x86_64-unknown-linux-gnu]}"
    end

    on_arm do
      url "${url[aarch64-unknown-linux-gnu]}"
      sha256 "${sha[aarch64-unknown-linux-gnu]}"
    end
  end

  # Silk hands Clang textual LLVM IR; no-libc targets need Clang 22 or newer.
  depends_on "llvm"

  def install
    # The compiler finds lib/silk/stdlib beside its own bin directory, after resolving symlinks.
    libexec.install "bin", "lib"
    (bin/"silk").write <<~SH
      #!/bin/bash
      # Use Homebrew's Clang unless SILK_CLANG or --clang picks another.
      export SILK_CLANG="\\\${SILK_CLANG:-#{Formula["llvm"].opt_bin}/clang}"
      exec "#{libexec}/bin/silk" "\\\$@"
    SH
  end

  test do
    assert_equal "silk v#{version}", shell_output("#{bin}/silk --version").strip
    system bin/"silk", "init", "hello"
    cd "hello" do
      assert_match "Hello, world!", shell_output("#{bin}/silk run")
    end
  end
end
RUBY

printf '%s\n' "$tag"
